function getRate(animalType, fat, snf) {
  fat = parseFloat(fat);
  snf = parseFloat(snf);
  if (isNaN(fat) || isNaN(snf)) return null;

  if (animalType === 'buffalo') {
    const fatKey = (Math.round(fat * 10) / 10).toFixed(1);
    const snfClamped = Math.min(Math.max(snf, 8.6), 10.0);
    const snfKey = (Math.round(snfClamped * 10) / 10).toFixed(1);
    const fatClamped = (Math.min(Math.max(parseFloat(fatKey), 4.5), 10.0)).toFixed(1);
    const row = BUFFALO_RATES_BASE[fatClamped];
    if (!row) return null;
    const colIdx = BUFFALO_SNF_COLS.findIndex(s => Math.abs(s - parseFloat(snfKey)) < 0.05);
    if (colIdx === -1) return null;
    return Math.round(row[colIdx] * 100) / 100;
  } else {
    const fatClamped = (Math.min(Math.max(fat, 3.0), 5.0)).toFixed(1);
    const snfClamped = (Math.min(Math.max(snf, 8.2), 9.0)).toFixed(1);
    const row = COW_RATES[fatClamped];
    if (!row) return null;
    const colIdx = COW_SNF_COLS.findIndex(s => Math.abs(s - parseFloat(snfClamped)) < 0.05);
    if (colIdx === -1) return null;
    return row[colIdx];
  }
}

function getRateInfo(animalType) {
  if (animalType === 'buffalo') {
    return { fatMin:4.5, fatMax:10.0, snfMin:8.6, snfMax:10.0, snfStep:0.1 };
  }
  return { fatMin:3.0, fatMax:5.0, snfMin:8.2, snfMax:9.0, snfStep:0.1 };
}

